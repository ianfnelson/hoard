using Hoard.Core.Application.Portfolios;
using QuestPDF.Drawing;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Hoard.Core.Infrastructure.Integrations;

public interface IPortfolioValuationsPdfService
{
    Stream Generate(string portfolioName, PortfolioValuationsDto valuations);
}

public class PortfolioValuationsPdfService : IPortfolioValuationsPdfService
{
    private const string FontFamily = "Inter";

    static PortfolioValuationsPdfService()
    {
        QuestPDF.Settings.License = LicenseType.Community;

        var assembly = typeof(PortfolioValuationsPdfService).Assembly;
        var ns = typeof(PortfolioValuationsPdfService).Namespace!;

        using var regular = assembly.GetManifestResourceStream($"{ns}.Fonts.Inter-Regular.ttf");
        if (regular != null) FontManager.RegisterFontFromStream(regular);

        using var bold = assembly.GetManifestResourceStream($"{ns}.Fonts.Inter-Bold.ttf");
        if (bold != null) FontManager.RegisterFontFromStream(bold);
    }

    public Stream Generate(string portfolioName, PortfolioValuationsDto valuations)
    {
        var hasFromDate = valuations.FromDate.HasValue;
        var sortedItems = SortItems(valuations.Items);

        var stream = new MemoryStream();

        Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4.Landscape());
                page.Margin(1.5f, Unit.Centimetre);
                page.DefaultTextStyle(x => x.FontFamily(FontFamily).FontSize(9));

                page.Header().Column(col =>
                {
                    col.Item().Text(portfolioName)
                        .Bold().FontSize(16);

                    var totalValue = valuations.Items
                        .Where(i => i.ToValue.HasValue)
                        .Sum(i => i.ToValue!.Value);

                    var dateRange = hasFromDate
                        ? $"{valuations.FromDate:dd MMMM yyyy} to {valuations.ToDate:dd MMMM yyyy}"
                        : $"Total valuation as at {valuations.ToDate:dd MMMM yyyy}: £{totalValue:N2}";
                    col.Item().Text(dateRange).FontSize(10);
                    col.Item().PaddingBottom(8);
                });

                page.Content().Element(c => ComposeTable(c, sortedItems, hasFromDate));

                page.Footer().Row(row =>
                {
                    row.RelativeItem().AlignLeft()
                        .Text($"Generated by Hoard {DateTime.UtcNow:dd MMM yyyy HH:mm} UTC")
                        .FontSize(7).FontColor(Colors.Grey.Medium);
                    row.RelativeItem().AlignRight()
                        .Text(text =>
                        {
                            text.Span("Page ").FontSize(7).FontColor(Colors.Grey.Medium);
                            text.CurrentPageNumber().FontSize(7).FontColor(Colors.Grey.Medium);
                            text.Span(" of ").FontSize(7).FontColor(Colors.Grey.Medium);
                            text.TotalPages().FontSize(7).FontColor(Colors.Grey.Medium);
                        });
                });
            });
        }).GeneratePdf(stream);

        stream.Position = 0;
        return stream;
    }

    private static List<PortfolioValuationItemDto> SortItems(IReadOnlyList<PortfolioValuationItemDto> items)
    {
        return items
            .OrderByDescending(x => x.ToValue.HasValue ? 1 : 0)
            .ThenByDescending(x => x.ToValue ?? 0)
            .ThenByDescending(x => x.FromValue ?? 0)
            .ToList();
    }

    private static void ComposeTable(
        IContainer container,
        List<PortfolioValuationItemDto> items,
        bool hasFromDate)
    {
        container.Table(table =>
        {
            table.ColumnsDefinition(columns =>
            {
                columns.ConstantColumn(50);  // Ticker
                columns.RelativeColumn(3);   // Name

                if (hasFromDate)
                {
                    columns.RelativeColumn();  // From Units
                    columns.RelativeColumn();  // From Value
                    columns.RelativeColumn();  // From %
                    columns.RelativeColumn();  // To Units
                    columns.RelativeColumn();  // To Value
                    columns.RelativeColumn();  // To %
                    columns.RelativeColumn();  // Change Value
                    columns.RelativeColumn();  // Change %
                }
                else
                {
                    columns.RelativeColumn();  // Units
                    columns.RelativeColumn();  // Value
                    columns.RelativeColumn();  // %
                }
            });

            table.Header(header =>
            {
                AddHeaderCell(header, "Ticker", false);
                AddHeaderCell(header, "Name", false);

                if (hasFromDate)
                {
                    AddHeaderCell(header, "From Units");
                    AddHeaderCell(header, "From Value");
                    AddHeaderCell(header, "From %");
                    AddHeaderCell(header, "To Units");
                    AddHeaderCell(header, "To Value");
                    AddHeaderCell(header, "To %");
                    AddHeaderCell(header, "Change Value");
                    AddHeaderCell(header, "Change %");
                }
                else
                {
                    AddHeaderCell(header, "Units");
                    AddHeaderCell(header, "Value");
                    AddHeaderCell(header, "%");
                }
            });

            foreach (var item in items)
            {
                AddDataCell(table, item.InstrumentTicker, false);
                AddDataCell(table, item.InstrumentName, false);

                if (hasFromDate)
                {
                    AddDataCell(table, FormatUnits(item.FromUnits));
                    AddDataCell(table, FormatCurrency(item.FromValue));
                    AddDataCell(table, FormatPercentage(item.FromPercentage));
                    AddDataCell(table, FormatUnits(item.ToUnits));
                    AddDataCell(table, FormatCurrency(item.ToValue));
                    AddDataCell(table, FormatPercentage(item.ToPercentage));
                    AddDataCell(table, FormatCurrency(item.ChangeValue));
                    AddDataCell(table, FormatPercentage(item.ChangePercentage));
                }
                else
                {
                    AddDataCell(table, FormatUnits(item.ToUnits));
                    AddDataCell(table, FormatCurrency(item.ToValue));
                    AddDataCell(table, FormatPercentage(item.ToPercentage));
                }
            }
        });
    }

    private static void AddHeaderCell(TableCellDescriptor header, string text, bool alignRight = true)
    {
        var cell = header.Cell().BorderBottom(1).BorderColor(Colors.Grey.Medium).Padding(4);
        var textBlock = alignRight ? cell.AlignRight().Text(text) : cell.Text(text);
        textBlock.Bold().FontSize(8);
    }

    private static void AddDataCell(TableDescriptor table, string text, bool alignRight = true)
    {
        var cell = table.Cell()
            .BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4);
        if (alignRight)
            cell.AlignRight().Text(text).FontSize(8);
        else
            cell.Text(text).FontSize(8);
    }

    private static string FormatCurrency(decimal? value) =>
        value.HasValue ? value.Value.ToString("N2") : "-";

    private static string FormatPercentage(decimal? value) =>
        value.HasValue ? $"{value.Value:N2}%" : "-";

    private static string FormatUnits(decimal? value) =>
        value.HasValue ? value.Value.ToString("N4") : "-";
}
